    related_entity_type varchar(30),
    title varchar(150) NOT NULL,
    type varchar(30) NOT NULL,
    updated_at timestamp with time zone,
    user_id bigint NOT NULL,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT notifications_related_entity_type_check CHECK (related_entity_type IN ('DATE', 'CHECKLIST_ITEM', 'CATEGORY', 'REMINDER', 'ATTACHMENT', 'MEMORY_FOLDER', 'MEMORY_PHOTO', 'LOVE_NOTE', 'LOVE_STICKER', 'USER')),
    CONSTRAINT notifications_type_check CHECK (type IN ('REMINDER', 'CHECKLIST_UPDATE', 'DATE_CREATED', 'DATE_COMPLETED', 'DATE_UPDATED', 'MEMORY_CREATED', 'MEMORY_UPDATED', 'MEMORY_DELETED', 'GALLERY_UPLOAD', 'LOVE_NOTE_CREATED', 'LOVE_NOTE_UPDATED', 'LOVE_NOTE_DELETED', 'PROFILE_CHANGED', 'ADMIN_ACTION', 'SYSTEM'))
);

