-- V1 baseline: the schema exactly as it exists in the live Supabase database
-- (captured read-only from information_schema / pg_indexes / pg_constraint).
--
-- On the live database this file is NEVER executed: Flyway is configured with
-- baseline-on-migrate=true and baseline-version=1, so it only records V1 as already
-- applied. It runs only against an empty database (local dev, CI, a fresh project).
--
-- Duplicate indexes (idx_memory_folders_archived / idx_memory_folders_is_archived and
-- idx_memory_photos_folder / idx_memory_photos_folder_id) are kept on purpose so this
-- file matches live; drop one of each in a later migration if desired.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    active boolean NOT NULL,
    created_at timestamp,
    last_login_at timestamp,
    name varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    updated_at timestamp,
    username varchar(50) NOT NULL,
    created_by bigint,
    accent_color varchar(20),
    avatar_storage_path text,
    avatar_url text,
    bio varchar(100),
    favorite_emoji varchar(8),
    nickname varchar(20),
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT ukr43af9ap4edm43mmtq01oddj6 UNIQUE (username),
    CONSTRAINT users_role_check CHECK (((role)::text = ANY (ARRAY[('ROLE_USER'::character varying)::text, ('ROLE_ADMIN'::character varying)::text])))
);

CREATE TABLE date_categories (
    id uuid NOT NULL,
    color_hex varchar(20),
    created_at timestamp with time zone,
    created_by bigint,
    deleted_at timestamp with time zone,
    description text,
    icon varchar(30),
    name varchar(60) NOT NULL,
    updated_at timestamp with time zone,
    CONSTRAINT date_categories_pkey PRIMARY KEY (id)
);

CREATE TABLE dates (
    id uuid NOT NULL,
    cover_image_url text,
    created_at timestamp with time zone,
    created_by bigint,
    deleted_at timestamp with time zone,
    description text,
    estimated_cost numeric(10,2),
    is_archived boolean,
    location varchar(200),
    planned_date date,
    priority varchar(10) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'DREAMING'::character varying,
    title varchar(150) NOT NULL,
    updated_at timestamp with time zone,
    category_id uuid,
    activity_type varchar(50),
    duration_minutes integer,
    planned_time time,
    reservation_status varchar(20) NOT NULL,
    special_occasion varchar(150),
    travel_method varchar(50),
    CONSTRAINT dates_pkey PRIMARY KEY (id),
    CONSTRAINT dates_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT dates_reservation_status_check CHECK (reservation_status IN ('NOT_NEEDED', 'PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT dates_status_check CHECK (status IN ('DREAMING', 'PLANNING', 'BOOKED', 'READY', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE checklist_items (
    id uuid NOT NULL,
    completed_at timestamp with time zone,
    completed_by bigint,
    created_at timestamp with time zone,
    created_by bigint,
    deleted_at timestamp with time zone,
    is_completed boolean,
    sort_order integer,
    title varchar(200) NOT NULL,
    updated_at timestamp with time zone,
    date_id uuid NOT NULL,
    description text,
    due_date date,
    priority varchar(10) NOT NULL,
    CONSTRAINT checklist_items_pkey PRIMARY KEY (id),
    CONSTRAINT checklist_items_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE TABLE reminders (
    id uuid NOT NULL,
    channel varchar(10) NOT NULL,
    created_at timestamp with time zone,
    deleted_at timestamp with time zone,
    is_sent boolean,
    message varchar(255),
    remind_at timestamp with time zone NOT NULL,
    sent_at timestamp with time zone,
    updated_at timestamp with time zone,
    user_id bigint NOT NULL,
    date_id uuid NOT NULL,
    CONSTRAINT reminders_pkey PRIMARY KEY (id),
    CONSTRAINT reminders_channel_check CHECK (channel IN ('APP', 'EMAIL'))
);

CREATE TABLE attachments (
    id uuid NOT NULL,
    attachable_id uuid NOT NULL,
    attachable_type varchar(20) NOT NULL,
    created_at timestamp with time zone,
    deleted_at timestamp with time zone,
    file_name varchar(255),
    file_size_bytes bigint,
    file_type varchar(50),
    file_url text NOT NULL,
    storage_path text NOT NULL,
    updated_at timestamp with time zone,
    uploaded_by bigint,
    CONSTRAINT attachments_pkey PRIMARY KEY (id),
    CONSTRAINT attachments_attachable_type_check CHECK (attachable_type IN ('DATE', 'CHECKLIST_ITEM'))
);

CREATE TABLE favorites (
    id uuid NOT NULL,
    created_at timestamp with time zone,
    deleted_at timestamp with time zone,
    favorable_id uuid NOT NULL,
    favorable_type varchar(20) NOT NULL,
    updated_at timestamp with time zone,
    user_id bigint NOT NULL,
    CONSTRAINT favorites_pkey PRIMARY KEY (id),
    CONSTRAINT favorites_favorable_type_check CHECK (favorable_type IN ('DATE', 'CHECKLIST_ITEM'))
);

CREATE TABLE activity_logs (
    id uuid NOT NULL,
    action varchar(50) NOT NULL,
    created_at timestamp with time zone DEFAULT now(),
    deleted_at timestamp with time zone,
    entity_id uuid,
    entity_type varchar(30) NOT NULL,
    metadata jsonb,
    updated_at timestamp with time zone,
    user_id bigint,
    status varchar(20) NOT NULL DEFAULT 'SUCCESS'::character varying,
    CONSTRAINT activity_logs_pkey PRIMARY KEY (id),
    CONSTRAINT activity_logs_entity_type_check CHECK (entity_type IN ('DATE', 'CHECKLIST_ITEM', 'CATEGORY', 'REMINDER', 'ATTACHMENT', 'MEMORY_FOLDER', 'MEMORY_PHOTO', 'LOVE_NOTE', 'LOVE_STICKER', 'USER'))
);

CREATE TABLE audit_trail (
    id uuid NOT NULL,
    action varchar(50) NOT NULL,
    actor_id bigint NOT NULL,
    after_data jsonb,
    before_data jsonb,
    changed_fields jsonb,
    created_at timestamp with time zone DEFAULT now(),
    entity varchar(50) NOT NULL,
    entity_id uuid,
    reason text,
    CONSTRAINT audit_trail_pkey PRIMARY KEY (id)
);

CREATE TABLE notifications (
    id uuid NOT NULL,
    created_at timestamp with time zone DEFAULT now(),
